def sylas_ult_group(name):
    """빼앗기 좋은 궁극기 종류 번호 (1~5). 목록에 없으면 None (별로)."""
    for i, group in enumerate(SYLAS_GOOD_ULTS, 1):
        if name in group:
            return i
    return None


def sylas_good(enemies):
    """상대 챔피언 목록에서 빼앗기 좋은 궁극기를 세어 사일러스를 뽑을 만한지 판단한다."""
    good = [(n, ULT_TYPES[sylas_ult_group(n) - 1]) for n in enemies if sylas_ult_group(n)]
    return len(good) >= 2, good
